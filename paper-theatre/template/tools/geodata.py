#!/usr/bin/env python3
"""Natural Earth (public domain, 1:50m) → film/geodata.js: land, lakes, rivers and one country's outline for the maps,
clipped to the film's map window and simplified for the cut-paper look. Run with python3 -I (standard library only).

film.json "map": {"box": [lon0, lat0, lon1, lat1], "country": "POL", "rivers": ["Vistula", "Oder"]}
- box: the window every map view must stay inside (a wide view past its edge shows bare card), so make it generous
- country: ADM0_A3 code of today's border to draw as a reference line (null for none)
- rivers: English names as in Natural Earth's river centrelines
The source files are downloaded once into research/geo_src/.
"""
import json
import math
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "research" / "geo_src"
NE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/{}.geojson"
CFG = json.loads((ROOT / "film.json").read_text(encoding="utf-8")).get("map", {})
BOX = tuple(CFG.get("box", [-12.0, 34.0, 45.0, 71.0]))
TOL = 0.035                                     # Douglas–Peucker tolerance in degrees (x scaled by cos of mid-latitude)
KX = math.cos(math.radians((BOX[1] + BOX[3]) / 2))


def source(name):
    path = SRC / f"{name}.geojson"
    if not path.exists():
        SRC.mkdir(parents=True, exist_ok=True)
        req = urllib.request.Request(NE.format(name), headers={"User-Agent": "paper-theatre geodata"})
        path.write_bytes(urllib.request.urlopen(req, timeout=60).read())
    return json.loads(path.read_text())["features"]


def clip(ring, box):
    """Sutherland–Hodgman against the rectangle (fine for filled shapes)."""
    x0, y0, x1, y1 = box
    def ix(a, b, x):
        t = (x - a[0]) / (b[0] - a[0]); return [x, a[1] + t * (b[1] - a[1])]
    def iy(a, b, y):
        t = (y - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), y]
    out = ring
    for inside, cut in ((lambda p: p[0] >= x0, lambda a, b: ix(a, b, x0)), (lambda p: p[0] <= x1, lambda a, b: ix(a, b, x1)),
                        (lambda p: p[1] >= y0, lambda a, b: iy(a, b, y0)), (lambda p: p[1] <= y1, lambda a, b: iy(a, b, y1))):
        if not out:
            break
        inp, out = out, []
        for i, cur in enumerate(inp):
            prev = inp[i - 1]
            if inside(cur):
                if not inside(prev):
                    out.append(cut(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(cut(prev, cur))
    return out


def simplify(pts, tol):
    """Douglas–Peucker."""
    if len(pts) < 3:
        return pts
    (ax, ay), (bx, by) = pts[0], pts[-1]
    dx, dy = (bx - ax) * KX, by - ay
    n = math.hypot(dx, dy)
    best, idx = -1.0, 0
    for i in range(1, len(pts) - 1):
        px, py = (pts[i][0] - ax) * KX, pts[i][1] - ay
        d = abs(px * dy - py * dx) / n if n > 1e-9 else math.hypot(px, py)
        if d > best:
            best, idx = d, i
    if best <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[: idx + 1], tol)[:-1] + simplify(pts[idx:], tol)


def area(r):
    return abs(sum(r[i - 1][0] * r[i][1] - r[i][0] * r[i - 1][1] for i in range(len(r)))) / 2 * KX


def rings(geom):
    return {"Polygon": lambda c: [c[0]], "MultiPolygon": lambda c: [p[0] for p in c]}.get(geom["type"], lambda c: [])(geom["coordinates"])


def polys(name, keep, min_area, tol=TOL):
    out = []
    for f in source(name):
        if keep(f["properties"]):
            for r in rings(f["geometry"]):
                c = clip([list(p) for p in r[:-1]], BOX)
                if len(c) >= 3 and area(c) >= min_area:
                    s = simplify(c + [c[0]], tol)[:-1]
                    if len(s) >= 3:
                        out.append([[round(x, 3), round(y, 3)] for x, y in s])
    return out


def main():
    land = polys("ne_50m_land", lambda p: True, 0.02)
    lakes = polys("ne_50m_lakes", lambda p: True, 0.04, 0.02)
    code = CFG.get("country")
    country = polys("ne_50m_admin_0_countries", lambda p: p.get("ADM0_A3") == code, 0.01, 0.02) if code else []
    want = set(CFG.get("rivers", []))
    rivers = {}
    for f in source("ne_50m_rivers_lake_centerlines") if want else []:
        name = f["properties"].get("name_en") or f["properties"].get("name") or ""
        if name not in want:
            continue
        g = f["geometry"]
        for ln in g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]:
            pts = [p for p in ln if BOX[0] <= p[0] <= BOX[2] and BOX[1] <= p[1] <= BOX[3]]
            if len(pts) >= 2:
                rivers.setdefault(name, []).append([[round(x, 3), round(y, 3)] for x, y in simplify(pts, 0.02)])
    js = ["// Generated by tools/geodata.py from Natural Earth 1:50m (public domain). [lon, lat] pairs.",
          f"// Window lon {BOX[0]}–{BOX[2]}, lat {BOX[1]}–{BOX[3]} (film.json \"map\"); Douglas–Peucker {TOL}°.",
          f"export const BOX = {json.dumps(list(BOX))};",
          f"export const LAND = {json.dumps(land, separators=(',', ':'))};",
          f"export const LAKES = {json.dumps(lakes, separators=(',', ':'))};",
          f"export const COUNTRY = {json.dumps(max(country, key=area) if country else [], separators=(',', ':'))};",
          f"export const RIVERS = {json.dumps(rivers, separators=(',', ':'))};", ""]
    (ROOT / "film" / "geodata.js").write_text("\n".join(js), encoding="utf-8")
    missing = want - set(rivers)
    print(f"land {len(land)} rings, lakes {len(lakes)}, country {code or '-'}, rivers {sorted(rivers)}"
          + (f"; not in Natural Earth 1:50m: {sorted(missing)}" if missing else ""))


if __name__ == "__main__":
    main()
