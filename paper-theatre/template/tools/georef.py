#!/usr/bin/env python3
"""Lines read off a published map figure → [lon, lat] for the film's maps (film/<name>.js).

    python3 -I tools/georef.py research/<name>.georef.json

The spec names the figure and its source, control points of known coordinates (pixel → lon/lat: towns, border
corners, confluences — spread over the figure) and the lines as pixel polylines read on the figure (a grid drawn
over a zoomed crop helps). An affine fit maps pixels to coordinates; the residual of every control point is printed
and written into the module's header, so the error is known and can be said on screen ("simplified, after …").

    {"figure": "research/fig2.png", "source": "L. Marks 2005, Przegląd Geologiczny 53, Fig. 2",
     "control": [[[640, 405], [21.012, 52.230]], ...],
     "lines": {"leszno": [[25, 473], [50, 465], ...], ...}}

A city plan adds "units": "m" (residuals in metres) and "digits": 5 (about 1 m); the default is km and 3 decimals.
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def solve3(a, b):
    """Solve a 3×3 linear system (Gaussian elimination with partial pivoting)."""
    m = [row[:] + [v] for row, v in zip(a, b)]
    for c in range(3):
        p = max(range(c, 3), key=lambda r: abs(m[r][c]))
        m[c], m[p] = m[p], m[c]
        for r in range(3):
            if r != c:
                f = m[r][c] / m[c][c]
                m[r] = [x - f * y for x, y in zip(m[r], m[c])]
    return [m[i][3] / m[i][i] for i in range(3)]


def fit(control):
    """Least-squares affine map (x, y, 1) → lon and → lat."""
    rows = [(x, y, 1.0) for (x, y), _ in control]
    ata = [[sum(r[i] * r[j] for r in rows) for j in range(3)] for i in range(3)]
    coef = []
    for k in range(2):
        atb = [sum(r[i] * g[k] for r, (_, g) in zip(rows, control)) for i in range(3)]
        coef.append(solve3(ata, atb))
    return lambda x, y: [coef[0][0] * x + coef[0][1] * y + coef[0][2], coef[1][0] * x + coef[1][1] * y + coef[1][2]]


def main():
    spec_path = Path(sys.argv[1]).resolve()
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    to_geo = fit(spec["control"])
    # a city plan needs metres and about 1 m of precision; a regional figure keeps km and 3 decimals (about 100 m)
    digits = spec.get("digits", 3)
    unit, scale = ("m", 1000.0) if spec.get("units") == "m" else ("km", 1.0)
    res = []
    for (px, g) in spec["control"]:
        lon, lat = to_geo(*px)
        km = math.hypot((lon - g[0]) * 111.32 * math.cos(math.radians(g[1])), (lat - g[1]) * 110.57)
        res.append(km * scale)
        print(f"control {px} → {g}: residual {km * scale:.1f} {unit}")
    lines = {k: [[round(v, digits) for v in to_geo(x, y)] for x, y in pts] for k, pts in spec["lines"].items()}
    name = spec_path.name.split(".")[0]
    out = ROOT / "film" / f"{name}.js"
    out.write_text(f"// Generated by tools/georef.py from {spec_path.relative_to(ROOT)}: lines read off {spec.get('source', spec['figure'])}.\n"
                   f"// Affine fit to {len(res)} control points, residuals {', '.join(f'{r:.0f}' for r in res)} {unit}. [lon, lat] pairs.\n"
                   f"export const {name.upper()} = {json.dumps(lines, separators=(',', ':'))};\n", encoding="utf-8")
    print(out.relative_to(ROOT), {k: len(v) for k, v in lines.items()})


if __name__ == "__main__":
    main()
